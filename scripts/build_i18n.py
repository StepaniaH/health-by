#!/usr/bin/env python3
"""Generate the browser catalog from the same JSON resources Python reads."""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent

def generated():
    messages = {lang: json.loads((ROOT / 'health_by/locales' / f'{lang}.json').read_text()) for lang in ('zh', 'en')}
    plurals = json.loads((ROOT / 'health_by/locales/plurals.json').read_text())
    return '// Generated by scripts/build_i18n.py; edit health_by/locales/*.json.\nexport const messages = ' + json.dumps(messages, ensure_ascii=False, indent=2) + ';\nexport const pluralParameters = ' + json.dumps(plurals, indent=2) + ';\n'

if __name__ == '__main__':
    (ROOT / 'health_by/web/js/i18n-messages.js').write_text(generated())
